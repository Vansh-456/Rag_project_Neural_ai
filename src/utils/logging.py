"""
Structured logging module for Adaptive Graph + Vector RAG.
Provides JSON or formatted structured logging across all sub-components.
"""

from __future__ import annotations

import logging
import sys
from typing import Any
import structlog


def setup_logger(log_level: str = "INFO", json_format: bool = False) -> structlog.BoundLogger:
    """Configures structured logging for stdout."""
    level = getattr(logging, log_level.upper(), logging.INFO)
    logging.basicConfig(
        format="%(message)s",
        stream=sys.stdout,
        level=level,
        force=True,
    )

    processors: list[Any] = [
        structlog.contextvars.merge_contextvars,
        structlog.processors.add_log_level,
        structlog.processors.TimeStamper(fmt="iso"),
        structlog.processors.StackInfoRenderer(),
        structlog.processors.format_exc_info,
    ]

    if json_format:
        processors.append(structlog.processors.JSONRenderer())
    else:
        processors.append(structlog.dev.ConsoleRenderer(colors=True))

    structlog.configure(
        processors=processors,
        wrapper_class=structlog.make_filtering_bound_logger(level),
        context_class=dict,
        logger_factory=structlog.PrintLoggerFactory(),
        cache_logger_on_first_use=True,
    )

    return structlog.get_logger("adaptive_rag")


logger = setup_logger()
